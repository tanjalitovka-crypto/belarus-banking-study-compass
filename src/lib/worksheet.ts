/* ---------- Normalisation & grading ---------- */

export function normalize(value: string): string {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"']/g, "")
    .replace(/[–—]/g, "-")
    .replace(/\s*-\s*/g, "-")
    .replace(/\s+/g, " ")
    .replace(/[.,;:!?]+$/g, "")
    .trim();
}

export function isAccepted(value: string, accepted: readonly string[]): boolean {
  const v = normalize(value);
  if (!v) return false;
  return accepted.some((a) => normalize(a) === v);
}

